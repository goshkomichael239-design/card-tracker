import { readFileSync, readdirSync, statSync } from 'node:fs'
import { createHash } from 'node:crypto'
import { join, relative, sep } from 'node:path'
import { defineConfig, type Plugin } from 'vite'
import react from '@vitejs/plugin-react'

// Every file in /public, as a path relative to it (these are copied to the
// build as they are, so the bundle does not list them).
const listPublicFiles = (dir: string, root = dir): string[] =>
  readdirSync(dir).flatMap((name) => {
    const path = join(dir, name)

    return statSync(path).isDirectory()
      ? listPublicFiles(path, root)
      : [relative(root, path).split(sep).join('/')]
  })

// Which of the two web builds this is (see src/app/channel.ts). The
// experimental one is built with VITE_CHANNEL=next and lives in next/.
const CHANNEL = process.env.VITE_CHANNEL === 'next' ? 'next' : 'stable'

/**
 * Writes sw.js into the build: it keeps the whole app (page, scripts, styles,
 * fonts, images, sounds, icons) in the browser's cache on first load, and then
 * serves it from there, so the installed app opens and works with no network.
 * The cache is named after the list of files, so a new build gets a new cache.
 */
const offlineCache = (): Plugin => ({
  name: 'card-tracker-offline-cache',
  apply: 'build',
  generateBundle(_options, bundle) {
    const publicFiles = listPublicFiles(join(process.cwd(), 'public')).filter(
      (file) => file !== 'sw.js',
    )
    const files = [
      './',
      ...Object.keys(bundle),
      ...publicFiles,
    ].sort()
    const version = createHash('sha1').update(files.join('\n')).digest('hex').slice(0, 10)

    this.emitFile({
      type: 'asset',
      fileName: 'sw.js',
      source: `// Generated by the build. Do not edit.
const CACHE = 'card-tracker-${CHANNEL}-${version}';
const FILES = ${JSON.stringify(files)};

self.addEventListener('install', (event) => {
  // A new version waits until the old one's windows are closed, so a page
  // that is open never loses the files it still needs.
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(FILES)));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(
          keys
            // Only this build's own old caches (the other build keeps its own);
            // the first release named them without the build's name.
            .filter((key) => (key.startsWith('card-tracker-${CHANNEL}-') || /^card-tracker-[0-9a-f]{10}$/.test(key)) && key !== CACHE)
            .map((key) => caches.delete(key)),
        ),
      )
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const request = event.request;

  if (request.method !== 'GET' || !request.url.startsWith(self.location.origin)) {
    return;
  }
${
      CHANNEL === 'stable'
        ? "\n  // The experimental build in next/ has its own worker and its own cache.\n  if (new URL(request.url).pathname.includes('/next/')) {\n    return;\n  }\n"
        : ''
    }

  event.respondWith(
    caches.match(request, { ignoreSearch: true }).then((cached) => {
      if (cached) {
        return cached;
      }

      return fetch(request)
        .then((response) => {
          if (response.ok) {
            const copy = response.clone();
            caches.open(CACHE).then((cache) => cache.put(request, copy));
          }

          return response;
        })
        .catch(() =>
          request.mode === 'navigate'
            ? caches.match('./', { ignoreSearch: true })
            : Response.error(),
        );
    }),
  );
});
`,
    })
  },
})

// https://vite.dev/config/
export default defineConfig({
  // Relative paths: the build works from any folder or address (GitHub Pages
  // under /name/, a phone's local server, or inside an Android wrapper).
  base: './',
  // The version of the app for the About screen.
  define: {
    __CHANNEL__: JSON.stringify(CHANNEL),
    __APP_VERSION__: JSON.stringify(
      (JSON.parse(readFileSync('package.json', 'utf8')) as { version: string })
        .version,
    ),
  },
  plugins: [react(), offlineCache()],
})
